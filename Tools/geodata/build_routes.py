#!/usr/bin/env python3
"""Generate the Debug-only preset routes for the map datum debug page.

Each preset is a centreline built from OpenStreetMap way geometries fetched by fetch_osm.py
(© OpenStreetMap contributors, ODbL 1.0): points are projected onto the route's main axis,
binned every BIN_METERS, and the median position of each bin is kept. This merges dual
carriageways and parallel tracks into one line that follows the road on a WGS-84 base map.

Usage: python3 -I build_routes.py <osm_dir> <output.swift>
"""
import json
import math
import pathlib
import statistics
import sys

BIN_METERS = 25.0

def main_line_only(tags: dict) -> bool:
    """Drops yards, sidings, crossovers and the Lok Ma Chau spur from the rail query."""
    return tags.get("usage") == "main" and "service" not in tags


def any_way(tags: dict) -> bool:
    return True


ROUTES = [
    ("beijing-changan", "Beijing · Chang'an Avenue", any_way),
    ("shanghai-nanjing-road", "Shanghai · Nanjing Road East", any_way),
    ("shenzhen-hongkong-lowu-rail", "Shenzhen → Hong Kong · Lo Wu rail", main_line_only),
    ("zhuhai-macau-gongbei", "Zhuhai → Macau · Gongbei", any_way),
    ("hongkong-nathan-road", "Hong Kong · Nathan Road", any_way),
    ("tokyo-chuo-dori", "Tokyo · Chuo-dori", any_way),
]


def centreline(elements: list[dict]) -> list[tuple[float, float]]:
    points = [(p["lat"], p["lon"]) for e in elements for p in e.get("geometry", [])]
    assert points, "no geometry"
    lat0 = statistics.fmean(p[0] for p in points)
    scale_x = 111_320.0 * math.cos(math.radians(lat0))
    scale_y = 110_540.0
    xy = [((lon - points[0][1]) * scale_x, (lat - points[0][0]) * scale_y) for lat, lon in points]
    # Main axis: the pair of extreme points along the longer bounding-box side.
    xs, ys = [p[0] for p in xy], [p[1] for p in xy]
    if max(xs) - min(xs) >= max(ys) - min(ys):
        a, b = xy[xs.index(min(xs))], xy[xs.index(max(xs))]
    else:
        a, b = xy[ys.index(min(ys))], xy[ys.index(max(ys))]
    length = math.hypot(b[0] - a[0], b[1] - a[1])
    ux, uy = (b[0] - a[0]) / length, (b[1] - a[1]) / length
    bins: dict[int, list[tuple[float, float]]] = {}
    for (x, y), (lat, lon) in zip(xy, points):
        t = (x - a[0]) * ux + (y - a[1]) * uy
        bins.setdefault(int(t // BIN_METERS), []).append((lat, lon))
    return [(statistics.median(p[0] for p in bins[k]), statistics.median(p[1] for p in bins[k]))
            for k in sorted(bins)]


def main() -> None:
    osm_dir, output = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    lines = [
        "// Generated by Tools/geodata/build_routes.py — do not edit.",
        "// Road geometry © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright).",
        "#if DEBUG",
        "",
        "/// Preset WGS-84 test routes for the map datum debug page.",
        "nonisolated enum MapDatumPresetRoutes {",
        "  struct Route: Identifiable, Sendable {",
        "    let id: String",
        "    let title: String",
        "    /// (latitude, longitude) pairs in WGS-84.",
        "    let points: [(Double, Double)]",
        "  }",
        "",
        "  static let all: [Route] = [",
    ]
    for route_id, title, keep in ROUTES:
        data = json.loads((osm_dir / "routes" / f"{route_id}.json").read_text())
        line = centreline([e for e in data["elements"] if keep(e.get("tags", {}))])
        print(f"{route_id}: {len(line)} points")
        lines.append(f'    Route(id: "{route_id}", title: "{title}", points: [')
        for lat, lon in line:
            lines.append(f"      ({lat:.6f}, {lon:.6f}),")
        lines.append("    ]),")
    lines += ["  ]", "}", "", "#endif", ""]
    output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
